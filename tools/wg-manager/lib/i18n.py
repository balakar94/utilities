def t(key):
    """Return localized string with fallback to en then key."""
    table = STRINGS.get(LANG, STRINGS["en"])
    val = table.get(key)
    if isinstance(val, str):
        return val
    fb = STRINGS["en"].get(key)
    if isinstance(fb, str):
        return fb
    return str(key)
def _confirm_tokens():
    table = CONFIRM_TOKENS.get(LANG, CONFIRM_TOKENS["en"])
    return table["yes"], table["no"]


def _norm_confirm(raw):
    text = str(raw).strip().lower()
    return text.replace("s\u00ed", "si")


def is_yes(raw):
    yes, _no = _confirm_tokens()
    v = _norm_confirm(raw)
    # All languages tolerate y/yes as affirmative.
    if v in ("y", "yes"):
        return True
    return v in yes


def is_no(raw):
    _yes, no = _confirm_tokens()
    return _norm_confirm(raw) in no


def choose_language():
    """Interactive language menu for --lang auto (step 1)."""
    global LANG
    aliases = {"1": "en", "en": "en", "english": "en", "2": "es", "es": "es", "espanol": "es", "spanish": "es", "3": "de", "de": "de", "deutsch": "de", "german": "de"}
    while True:
        print(t("lang_menu_title"))
        print("  1) English")
        print("  2) Espanol")
        print("  3) Deutsch")
        try:
            raw = input(t("lang_prompt")).strip().lower()
        except EOFError:
            LANG = "en"
            return LANG
        if raw == "espa\u00f1ol":
            LANG = "es"
            return LANG
        if raw in aliases:
            LANG = aliases[raw]
            return LANG
        print(t("lang_invalid"), file=sys.stderr)


def detect_system_lang():
    """Detect language from env: LANGUAGE first tag, else LC_ALL, else LANG."""
    for key in ("LANGUAGE", "LC_ALL", "LANG"):
        raw = os.environ.get(key, "")
        if not raw:
            continue
        # LANGUAGE may be colon-separated list, take first tag.
        first = str(raw).split(":")[0].strip()
        if not first:
            continue
        norm = first.strip().lower().replace("-", "_")
        # Values like es_ES.UTF-8, de_DE, en_US -> prefix before _ or . or @.
        tag = re.split(r"[_.@]", norm)[0] if norm else ""
        if not tag:
            continue
        if tag.startswith("es"):
            return "es"
        if tag.startswith("de"):
            return "de"
        # en, C, POSIX, empty and anything else fall back to en.
        if tag.startswith("en") or tag in ("c", "posix"):
            return "en"
        return "en"
    return "en"


def resolve_auto_lang(is_tty):
    """Resolve --lang auto: TTY uses env es/de silently else menu; non-TTY never prompts."""
    global LANG
    detected = detect_system_lang()
    if is_tty:
        if detected in ("es", "de"):
            LANG = detected
            return LANG
        return choose_language()
    LANG = detected or "en"
    return LANG


def set_language(lang):
    """Explicitly set global LANG."""
    global LANG
    if lang in ("en", "es", "de"):
        LANG = lang
    elif lang == "auto":
        LANG = detect_system_lang()
    else:
        LANG = "en"
    return LANG


def current_lang():
    """Return currently active language code."""
    return LANG or "en"



